public class VarDemo {
    public static void main(String[] args) {
        int age = 18;
        double score = 95.5;
        boolean isOk = true;
        char gender = '男';

        System.out.println("年龄：" + age);
        System.out.println("分数：" + score);
        System.out.println("是否合格：" + isOk);
        System.out.println("性别：" + gender);
    }
}